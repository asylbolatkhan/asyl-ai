def name(param: str, lang: str, short: bool = False) -> str:
    meta = DISCRETE.get(param) or SIGNALS.get(param)
    if meta is None:
        return param
    if short and f"short_{lang}" in meta:
        return meta[f"short_{lang}"]
    return meta[lang]


def unit(param: str) -> str:
    meta = DISCRETE.get(param) or SIGNALS.get(param) or {}
    return meta.get("unit", "")
