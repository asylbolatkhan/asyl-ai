"""Команданың бір файлдық Asyl AI интерфейсін бөлек файлдарға бөлу (бір рет іске қосылады).

    python scripts/split_team_html.py "C:/Users/.../index.html"

Нәтиже / Результат:
    web/index.html      — разметка
    web/css/styles.css  — стильдер
    web/js/data.js      — зерттеу деректері (STUDY, WAVES, STUDYSTATS, COHORT)
    web/js/assets.js    — суреттер (STUDIO_ART, liveAssets)
    web/js/app.js       — интерфейс логикасы
Логика өзгермейді: скрипттер сол ретпен жүктеледі (классикалық <script>, ортақ глобал аймақ).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"


def main(src_path: str) -> None:
    src = Path(src_path).read_text(encoding="utf-8")
    head_end = src.index("</head>")
    styles = re.findall(r"<style>(.*?)</style>", src[:head_end], flags=re.S)
    body_start = src.index("<body>") + len("<body>")
    script_start = src.index("<script>", body_start)
    markup = src[body_start:script_start]
    script = src[script_start + len("<script>"):src.rindex("</script>")]

    data_lines, asset_lines, app_lines = [], [], []
    for line in script.split("\n"):
        if line.startswith("const STUDY ="):
            data_lines.append(line)
        elif line.startswith("const STUDIO_ART=") or line.startswith("const liveAssets="):
            asset_lines.append(line)
        else:
            app_lines.append(line)
    assert len(data_lines) == 1 and len(asset_lines) == 2, (len(data_lines), len(asset_lines))

    (WEB / "css").mkdir(parents=True, exist_ok=True)
    (WEB / "js").mkdir(parents=True, exist_ok=True)
    (WEB / "css" / "styles.css").write_text("\n".join(s.strip("\n") for s in styles) + "\n", encoding="utf-8")
    hdr = "// Generated by scripts/split_team_html.py — source data, do not edit by hand.\n"
    (WEB / "js" / "data.js").write_text(hdr + data_lines[0] + "\n", encoding="utf-8")
    (WEB / "js" / "assets.js").write_text(hdr + "\n".join(asset_lines) + "\n", encoding="utf-8")
    (WEB / "js" / "app.js").write_text("\n".join(app_lines).strip("\n") + "\n", encoding="utf-8")
    index = f"""<!doctype html>
<html lang="kk">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Asyl AI</title>
<link rel="stylesheet" href="css/styles.css">
<link rel="stylesheet" href="css/gaitlens.css">
</head>
<body>{markup.rstrip()}
<script src="js/data.js"></script>
<script src="js/assets.js"></script>
<script src="js/analysis.js"></script>
<script src="js/app.js"></script>
<script src="js/gaitlens.js"></script>
</body>
</html>
"""
    (WEB / "index.html").write_text(index, encoding="utf-8")
    for p in sorted(WEB.rglob("*.*")):
        print(f"{p.relative_to(ROOT)}  {p.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main(sys.argv[1])
