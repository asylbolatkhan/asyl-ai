function glMarkdown(md) {
  let out = [], list = false;
  for (let line of md.split('\n')) {
    let s = line.trim(); if (!s) continue;
    let inline = x => E(x).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
    if (/^[-*•]\s/.test(s)) { if (!list) { out.push('<ul>'); list = true } out.push(`<li>${inline(s.slice(2))}</li>`); continue }
    if (list) { out.push('</ul>'); list = false }
    s = s.replace(/^#+\s*/, '');
    if (/^\*\*.+\*\*$/.test(s)) { out.push(`</section><section><h4>${inline(s.slice(2, -2))}</h4>`); continue }
    out.push(`<p>${inline(s)}</p>`);
  }
  if (list) out.push('</ul>');
  return ('<section>' + out.join('') + '</section>').replace('<section></section>', '');
}

function glSections(secs) {
  return secs.map(([title, lines]) => `<section><h4>${E(title)}</h4><ul>${lines.map(([txt, kind]) =>
    `<li class="${kind || ''}">${E(txt).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')}</li>`).join('')}</ul></section>`).join('');
}

